// One-time generator for the Tier G metadata split (speed fix, 2026-11-19).
// Reads src/data/tools.ts (via esbuild bundle, like split-blog-data.cjs)
// and emits src/data/toolsMeta.ts: a light metadata-only module
// (ToolMeta = slug/name/shortDescription/category/seoTitle/seoDescription)
// plus TOOL_CATEGORIES and TOOL_META_BY_SLUG.
//
// The entry bundle only needs metadata for the home directory, header and
// hero; full tool definitions (how-to steps, features, FAQs) stay in
// tools.ts and load with the tool-page chunks that actually use them.
// Re-run after editing tools.ts metadata; the generated file is committed.
'use strict';
const { execSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');

const REPO_ROOT = path.resolve(__dirname, '..');
const TOOLS_TS = path.join(REPO_ROOT, 'src', 'data', 'tools.ts');
const OUT = path.join(REPO_ROOT, 'src', 'data', 'toolsMeta.ts');

function main() {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'tools-meta-'));
  const bundled = path.join(tmpDir, 'tools.cjs');
  execSync(
    `${path.join(REPO_ROOT, 'node_modules', 'esbuild', 'bin', 'esbuild')} ` +
      `${TOOLS_TS} --bundle --format=cjs --platform=node --outfile=${bundled} --log-level=error`,
    { cwd: REPO_ROOT, stdio: 'inherit' },
  );
  const { TOOLS_REGISTRY, TOOL_CATEGORIES } = require(bundled);

  // JSON.stringify is the escaping workhorse (same pattern as
  // split-blog-data.cjs): values are data, never hand-built source.
  const metas = TOOLS_REGISTRY.map((t) => ({
    slug: t.slug,
    name: t.name,
    shortDescription: t.shortDescription,
    category: t.category,
    seoTitle: t.seoTitle,
    seoDescription: t.seoDescription,
  }));

  const lines = [];
  lines.push('// GENERATED by scripts/generate-tools-meta.cjs — do not edit by hand.');
  lines.push('// Re-run the generator after changing tool metadata in src/data/tools.ts.');
  lines.push('// Tier G of the speed fix (2026-11-19): the entry bundle needs only');
  lines.push('// this light metadata (home directory, header, hero); full tool');
  lines.push('// definitions stay in tools.ts and load with the tool-page chunks.');
  lines.push('');
  lines.push("export type { ToolCategoryId, ToolCategoryMeta } from './tools';");
  lines.push('');
  lines.push('/** Light tool metadata — the subset the entry bundle needs. */');
  lines.push('export interface ToolMeta {');
  lines.push('  slug: string;');
  lines.push('  name: string;');
  lines.push('  shortDescription: string;');
  lines.push('  category: ToolCategoryId;');
  lines.push('  seoTitle: string;');
  lines.push('  seoDescription: string;');
  lines.push('}');
  lines.push('');
  lines.push(
    'export const TOOL_CATEGORIES: ToolCategoryMeta[] = ' +
      JSON.stringify(TOOL_CATEGORIES, null, 2) +
      ';',
  );
  lines.push('');
  lines.push('export const TOOLS_META: ToolMeta[] = ' + JSON.stringify(metas, null, 2) + ';');
  lines.push('');
  lines.push('export const TOOL_META_BY_SLUG: Record<string, ToolMeta> = Object.fromEntries(');
  lines.push('  TOOLS_META.map((t) => [t.slug, t]),');
  lines.push(');');
  lines.push('');

  fs.writeFileSync(OUT, lines.join('\n'));
  console.log(`[tools-meta] wrote ${metas.length} tool metas to src/data/toolsMeta.ts`);
}

main();
