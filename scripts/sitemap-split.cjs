// Shared sitemap index/parts helpers (sitemap split, 2026-11-22).
//
// WHY: Cloudflare Pages rejects any single file over 25 MiB, and
// public/sitemap.xml grew to 44 MiB (3,519 URLs), which failed the
// production deploy 894605a1 at asset validation. The sitemap is therefore
// split: public/sitemap.xml is a sitemap-index listing
// public/sitemap-1.xml ... public/sitemap-N.xml, each part holding whole
// <url> entries chunked by byte size (15 MiB budget per part, well under
// the 25 MiB Cloudflare limit and the 50,000-URL protocol limit).
//
// CONTENT IS PRESERVED BYTE-IDENTICAL: entries are moved, never rewritten
// (including the duplicated hreflang lines inside the non-blog entries —
// deduping them would shrink the file to ~4 MB, but that is a separate
// content change, NOT part of this split).
//
// CANONICAL SOURCES: non-blog entries live in scripts/sitemap-nonblog.xml
// (hand-maintained); blog entries are generated by
// scripts/generate-blog-sitemap.cjs. The generator assembles both and
// writes the index + parts. Consumers (check-sitemap, prerender-ssr,
// prerender) read through readSitemapEntries() here, which resolves the
// index to its parts (and still handles a legacy single-file urlset).
'use strict';
const fs = require('fs');
const path = require('path');

const BASE = 'https://compressmypic.online';
// 15 MiB per part: comfortable margin below Cloudflare's 25 MiB limit even
// after several more languages are added (each adds ~58 non-blog URLs at
// ~40 KB each ≈ 2.3 MB, spread across parts by the sequential chunker).
const PART_BUDGET_BYTES = 15 * 1024 * 1024;
// Sitemap protocol limit per file.
const PART_MAX_URLS = 50000;
// check-sitemap.cjs fails any part over this (margin below the 25 MiB
// Cloudflare limit, so a part can never silently grow past it).
const CHECK_MAX_BYTES = 20 * 1024 * 1024;

const URLSET_HEADER =
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">';
const URLSET_FOOTER = '</urlset>';
const INDEX_HEADER =
  '<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">';
const INDEX_FOOTER = '</sitemapindex>';

/** Whole `  <url>...</url>` blocks, in file order. */
function extractUrlBlocks(xml) {
  return [...xml.matchAll(/  <url>[\s\S]*?  <\/url>/g)].map((m) => m[0]);
}

function partFileName(i) {
  return `sitemap-${i}.xml`;
}

/** Sequential byte-budget chunking: whole entries, in order, each part
 *  <= PART_BUDGET_BYTES and <= PART_MAX_URLS. Growth adds parts; no entry
 *  ever moves unless an earlier entry changes size. */
function chunkEntries(entries) {
  const wrapperBytes = Buffer.byteLength(`${URLSET_HEADER}\n${URLSET_FOOTER}\n`);
  const parts = [];
  let cur = [];
  let curBytes = wrapperBytes;
  for (const e of entries) {
    const b = Buffer.byteLength(`${e}\n`);
    if (cur.length > 0 && (curBytes + b > PART_BUDGET_BYTES || cur.length >= PART_MAX_URLS)) {
      parts.push(cur);
      cur = [];
      curBytes = wrapperBytes;
    }
    cur.push(e);
    curBytes += b;
  }
  if (cur.length > 0) parts.push(cur);
  return parts;
}

function renderPart(entries) {
  return `${URLSET_HEADER}\n${entries.join('\n')}\n${URLSET_FOOTER}\n`;
}

function renderIndex(partNames) {
  const lines = partNames.map(
    (n) => `  <sitemap>\n    <loc>${BASE}/${n}</loc>\n  </sitemap>`
  );
  return `${INDEX_HEADER}\n${lines.join('\n')}\n${INDEX_FOOTER}\n`;
}

/** File map { filename: contents } for the index + parts, plus per-part
 *  info ({ name, urls, bytes }). Deterministic for a given entry list. */
function buildFileMap(entries) {
  const parts = chunkEntries(entries);
  const map = {};
  const names = parts.map((_, i) => partFileName(i + 1));
  names.forEach((n, i) => {
    map[n] = renderPart(parts[i]);
  });
  map['sitemap.xml'] = renderIndex(names);
  return {
    map,
    parts: names.map((n, i) => ({
      name: n,
      urls: parts[i].length,
      bytes: Buffer.byteLength(map[n]),
    })),
  };
}

/** Write the index + parts to publicDir (temp file + rename each), removing
 *  stale sitemap-N.xml files beyond the new count. Returns part info. */
function writeSitemapParts(entries, publicDir) {
  const { map, parts } = buildFileMap(entries);
  for (const [name, contents] of Object.entries(map)) {
    const tmp = path.join(publicDir, `${name}.tmp`);
    fs.writeFileSync(tmp, contents);
    fs.renameSync(tmp, path.join(publicDir, name));
  }
  let i = parts.length + 1;
  for (;;) {
    const stale = path.join(publicDir, partFileName(i));
    if (!fs.existsSync(stale)) break;
    fs.unlinkSync(stale);
    i += 1;
  }
  return parts;
}

/** Read the sitemap as the union of <url> entries across the index + parts.
 *  Returns { entries, parts, index } where parts are the part filenames
 *  listed in the index (or ['sitemap.xml'] for a legacy single-file
 *  urlset). */
function readSitemapEntries(publicDir) {
  const indexPath = path.join(publicDir, 'sitemap.xml');
  const xml = fs.readFileSync(indexPath, 'utf8');
  if (xml.includes('<sitemapindex')) {
    const partNames = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)]
      .map((m) => m[1].trim())
      .filter((u) => u.startsWith(`${BASE}/`))
      .map((u) => u.slice(BASE.length + 1));
    const entries = [];
    for (const name of partNames) {
      const partXml = fs.readFileSync(path.join(publicDir, name), 'utf8');
      entries.push(...extractUrlBlocks(partXml));
    }
    return { entries, parts: partNames, index: true };
  }
  return { entries: extractUrlBlocks(xml), parts: ['sitemap.xml'], index: false };
}

module.exports = {
  BASE,
  PART_BUDGET_BYTES,
  PART_MAX_URLS,
  CHECK_MAX_BYTES,
  extractUrlBlocks,
  chunkEntries,
  buildFileMap,
  writeSitemapParts,
  readSitemapEntries,
  partFileName,
};
