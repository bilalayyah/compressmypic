#!/usr/bin/env node
/**
 * ONE-TIME migration (speed fix Tier B, 2026-11-19): split the EN blog
 * bodies + FAQs out of src/data/blogArticles.ts.
 *
 * BEFORE: blogArticles.ts held all 144 articles' full bodies (~639 KiB
 * gzip) and was statically imported by App.tsx, so the bodies shipped in
 * the entry bundle on EVERY page.
 *
 * AFTER:
 *  - src/data/blogArticles.ts keeps the registry + helpers, but each
 *    article is metadata only (id, toolSlug, categoryId, type, status,
 *    publishedAt, updatedAt?, en.{slug,title,description,readingMinutes},
 *    relatedToolSlugs). The export name stays BLOG_ARTICLES and the field
 *    order/shape stay parser-compatible with scripts/generate-blog-sitemap.cjs
 *    and scripts/check-sitemap.cjs (single-quoted strings, `id:` first,
 *    `en: { slug: ...`).
 *  - src/data/blog-bodies/<articleId>.ts holds one article's BODY + FAQS.
 *  - src/data/blogBody.ts (hand-written) loads + caches them.
 *
 * Run once from the repo root: node scripts/split-blog-data.cjs
 * It refuses to run twice (the input registry must still contain bodies).
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const REPO_ROOT = path.resolve(__dirname, '..');
const REGISTRY = path.join(REPO_ROOT, 'src', 'data', 'blogArticles.ts');
const BODIES_DIR = path.join(REPO_ROOT, 'src', 'data', 'blog-bodies');

// Single-quoted TS string literal (matches the registry's existing style
// AND the sitemap scripts' regexes, which expect '...' quotes).
function q(s) {
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

function main() {
  // 1. Bundle the current (full) registry with esbuild and read the data.
  const bundled = '/tmp/blog-full-split.cjs';
  execSync(
    `${path.join(REPO_ROOT, 'node_modules', 'esbuild', 'bin', 'esbuild')} ` +
      `${REGISTRY} --bundle --format=cjs --platform=node --outfile=${bundled} --log-level=error`,
    { cwd: REPO_ROOT, stdio: 'inherit' },
  );
  const { BLOG_ARTICLES } = require(bundled);
  if (!Array.isArray(BLOG_ARTICLES) || BLOG_ARTICLES.length === 0) {
    throw new Error('no articles found in bundled registry');
  }
  if (!BLOG_ARTICLES[0].en || typeof BLOG_ARTICLES[0].en.body !== 'string') {
    throw new Error('registry no longer contains bodies — split already done? refusing to run twice');
  }
  console.log(`[split] ${BLOG_ARTICLES.length} articles with bodies`);

  // 2. Emit one body module per article.
  fs.mkdirSync(BODIES_DIR, { recursive: true });
  for (const a of BLOG_ARTICLES) {
    const out = path.join(BODIES_DIR, `${a.id}.ts`);
    const content =
      `// Generated by scripts/split-blog-data.cjs (one-time split, 2026-11-19)\n` +
      `// from src/data/blogArticles.ts. Body + FAQs for article '${a.id}'.\n` +
      `// This file is the single source for this article's body text.\n` +
      `import type { BlogArticleFaq } from '../../types/blog';\n\n` +
      `export const BODY: string = ${JSON.stringify(a.en.body)};\n\n` +
      `export const FAQS: BlogArticleFaq[] = ${JSON.stringify(a.en.faqs ?? [])};\n`;
    fs.writeFileSync(out, content, 'utf8');
  }
  console.log(`[split] wrote ${BLOG_ARTICLES.length} body modules to src/data/blog-bodies/`);

  // 3. Rewrite the registry: metadata array only.
  let src = fs.readFileSync(REGISTRY, 'utf8');
  const arrStart = src.indexOf('export const BLOG_ARTICLES');
  if (arrStart === -1) throw new Error('BLOG_ARTICLES declaration not found');
  const eqBracket = src.indexOf('= [', arrStart);
  if (eqBracket === -1) throw new Error('BLOG_ARTICLES array literal not found');
  const arrEnd = src.indexOf('\n];', eqBracket);
  if (arrEnd === -1) throw new Error('BLOG_ARTICLES array end not found');

  const entries = BLOG_ARTICLES.map((a) => {
    const lines = [
      '    {',
      `      id: ${q(a.id)},`,
      `      toolSlug: ${q(a.toolSlug)},`,
      `      categoryId: ${q(a.categoryId)},`,
      `      type: ${q(a.type)},`,
      `      status: ${q(a.status)},`,
      `      publishedAt: ${q(a.publishedAt)},`,
    ];
    if (a.updatedAt) lines.push(`      updatedAt: ${q(a.updatedAt)},`);
    lines.push(
      '      en: {',
      `        slug: ${q(a.en.slug)},`,
      `        title: ${q(a.en.title)},`,
      `        description: ${q(a.en.description)},`,
      `        readingMinutes: ${a.en.readingMinutes},`,
      '      },',
      `      relatedToolSlugs: [${(a.relatedToolSlugs ?? []).map(q).join(', ')}],`,
      '    },',
    );
    return lines.join('\n');
  }).join('\n');

  const newArray =
    'export const BLOG_ARTICLES: BlogArticleMeta[] = [\n' + entries + '\n];';
  src = src.slice(0, arrStart) + newArray + src.slice(arrEnd + 3);

  // 4. Type renames: BlogArticle -> BlogArticleMeta (whole word only; the
  // locale-version/override/faq types and getBlogArticle* helpers are
  // untouched because the word boundary fails inside them).
  const renamed = src.replace(/\bBlogArticle\b/g, 'BlogArticleMeta');
  const renameCount = (src.match(/\bBlogArticle\b/g) || []).length;
  src = renamed;
  console.log(`[split] renamed ${renameCount} BlogArticle -> BlogArticleMeta references`);

  // 5. getBlogArticleVersion: bodies now come from the body module (enBody
  // param) or the locale override — never from the registry itself.
  const oldVersionFn = `/** The version to render in \`lang\`: the locale override layered over EN
 *  (missing override -> EN content with the localized slug). */
export function getBlogArticleVersion(
  article: BlogArticleMeta,
  lang: SupportedLang,
  overrides: Record<string, BlogArticleLocaleOverride> = {},
): BlogArticleLocaleVersion {
  const base = article.en;
  const slug = getBlogArticleSlug(article, lang);
  if (lang === 'en') return base;
  const o = overrides[article.id];
  if (!o) return { ...base, slug };
  return {
    slug,
    title: o.title,
    description: o.description,
    body: o.body,
    faqs: o.faqs ?? base.faqs,
    readingMinutes: o.readingMinutes,
  };
}`;
  const newVersionFn = `/** The version to render in \`lang\`: the locale override layered over EN
 *  (missing override -> EN content with the localized slug).
 *  Bodies + FAQs no longer live in the registry (Tier B speed fix): the EN
 *  body comes from \`enBody\` (src/data/blogBody.ts — preloaded by main.tsx
 *  on article routes, loaded on demand elsewhere). Callers that only need
 *  title/description/readingMinutes (cards, search, SEO titles) may omit
 *  it; they get an empty body, which they must not render. */
export function getBlogArticleVersion(
  article: BlogArticleMeta,
  lang: SupportedLang,
  overrides: Record<string, BlogArticleLocaleOverride> = {},
  enBody?: BlogBodyData,
): BlogArticleLocaleVersion {
  const base = article.en;
  const slug = getBlogArticleSlug(article, lang);
  if (lang === 'en') {
    return {
      slug,
      title: base.title,
      description: base.description,
      body: enBody?.body ?? '',
      faqs: enBody?.faqs ?? [],
      readingMinutes: base.readingMinutes,
    };
  }
  const o = overrides[article.id];
  if (!o) {
    return {
      slug,
      title: base.title,
      description: base.description,
      body: enBody?.body ?? '',
      faqs: enBody?.faqs ?? [],
      readingMinutes: base.readingMinutes,
    };
  }
  return {
    slug,
    title: o.title,
    description: o.description,
    body: o.body,
    faqs: o.faqs ?? enBody?.faqs ?? [],
    readingMinutes: o.readingMinutes,
  };
}`;
  if (!src.includes(oldVersionFn)) throw new Error('getBlogArticleVersion text not found — file changed?');
  src = src.replace(oldVersionFn, newVersionFn);

  // 6. Import the BlogBodyData type.
  const importAnchor = `import type {
  BlogArticleMeta,
  BlogArticleLocaleOverride,
  BlogArticleLocaleVersion,
  BlogRoute,
} from '../types/blog';`;
  if (!src.includes(importAnchor)) throw new Error('types/blog import block not found');
  src = src.replace(
    importAnchor,
    importAnchor + `\nimport type { BlogBodyData } from './blogBody';`,
  );

  fs.writeFileSync(REGISTRY, src, 'utf8');
  console.log('[split] registry rewritten (metadata only)');

  // 7. Verify: every meta id has a body file, and counts match.
  const written = fs.readdirSync(BODIES_DIR).filter((f) => f.endsWith('.ts'));
  if (written.length !== BLOG_ARTICLES.length) {
    throw new Error(`body file count mismatch: ${written.length} files vs ${BLOG_ARTICLES.length} articles`);
  }
  for (const a of BLOG_ARTICLES) {
    if (!fs.existsSync(path.join(BODIES_DIR, `${a.id}.ts`))) {
      throw new Error(`missing body file for ${a.id}`);
    }
  }
  console.log('[split] verified: all body files present');
}

main();
