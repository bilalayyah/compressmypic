function localeFromPath(pathname: string): SupportedLang | null {
  const firstSegment = pathname.toLowerCase().split('/').filter(Boolean)[0] ?? '';
  return isSupportedLang(firstSegment) && firstSegment !== 'en' ? firstSegment : null;
}

async function preloadLocale(lang: SupportedLang, opts?: { withBlog?: boolean }): Promise<void> {
  // One shared loader for boot and App (src/locales/loadLocaleData.ts):
  // same module specifiers, so Vite serves the same chunks from its module
  // cache when App mounts. The assembled object goes into the locale
  // cache, not just the module cache — App's first render reads it.
  const data = await loadLocaleData(lang, opts);
  setCachedLocale(lang, data);
}

// CLS, second half — preload the route's lazy page chunk (same issue 4).
// Measured (2026-11-14, local render check): the locale preload alone left
// DE CLS at 0.7852, because App renders its route pages with React.lazy +
// a short "Loading…" Suspense fallback; while the page chunk downloads, the
// page is short, the footer sits near the top, and when the chunk arrives
// the footer jumps ~7,400px down (one 0.705 shift). Preloading the chunk
// here — same module specifiers App.tsx's lazy() calls use, so Vite serves
// the same chunk from its module cache — makes React.lazy resolve
// synchronously on first render, so the fallback never paints and the
// footer never jumps. The route -> page mapping below was extracted from
// App.tsx's page router (see scripts/prerender.cjs header for the
// regenerating approach); it must be updated if routes or page components
// are renamed — a stale entry only costs a missed preload, never a crash,
// because resolvePageModule returns null for anything it cannot map.
// Tables generated by scripts/generate-page-map.cjs (dev tool — parses
// App.tsx's router branches + lazy imports; not part of the build).
const topLevelPages = import.meta.glob('./pages/*.tsx');
const nestedPages = import.meta.glob('./pages/*/*.tsx');

const EN_PATH_BY_LANG: Record<string, Record<string, string> | undefined> = {
  es: EN_PATH_BY_ES,
  pt: EN_PATH_BY_PT,
  fr: EN_PATH_BY_FR,
  de: EN_PATH_BY_DE,
  it: EN_PATH_BY_IT,
  id: EN_PATH_BY_ID,
  ru: EN_PATH_BY_RU,
  ja: EN_PATH_BY_JA,
  ko: EN_PATH_BY_KO,
  zh: EN_PATH_BY_ZH,
  tr: EN_PATH_BY_TR,
};

function resolvePageModule(pathname: string): string | null {
  const clean = pathname.toLowerCase().replace(/\/+$/, '') || '/';
  if (clean === '/') return null; // home renders inline (renderHome) — no lazy page
  const dirModule = DIRECTORY_PAGE_MODULES[clean];
  if (dirModule) return dirModule;
  const firstSegment = clean.split('/').filter(Boolean)[0] ?? '';
  const lang: SupportedLang = isSupportedLang(firstSegment) ? firstSegment : 'en';
  const enPath =
    lang === 'en' ? clean : EN_PATH_BY_LANG[lang]?.[clean];
  // No EN path: a home alias (e.g. /de/bilder-komprimieren) or an unknown
  // path (404 page) — nothing to preload, App handles both itself.
  if (!enPath) return null;
  // Blog routes (Batch 2): one page component per route kind, shared by all
  // languages — resolve by kind, not by slug. (Draft articles resolve to
  // null here; App 404s them.)
  if (isBlogEnPath(enPath)) {
    const blogRoute = resolveBlogRoute(enPath);
    if (!blogRoute) return null;
    return BLOG_PAGE_MODULES[blogRoute.kind] ?? null;
  }
  return TOOL_PAGE_MODULES[enPath] ?? LOCALIZED_PAGE_MODULES[`${lang}|${enPath}`] ?? null;
}

async function preloadPage(pathname: string): Promise<void> {
  const globKey = resolvePageModule(pathname);
  if (!globKey) return;
  const loader = topLevelPages[globKey] ?? nestedPages[globKey];
  if (loader) await loader();
}

async function start(): Promise<void> {
  // H5 (re-audit 2026-11-15): the entry bundle must mount exactly once per
  // page load. A second execution (e.g. if the entry is ever loaded twice
  // under two URLs again, as in the H1 dual-bundle defect) would create a
  // second React root and fire a second pageview + tool_used. The flag lives
  // on window because two executions have separate module scopes — a
  // module-level flag would not be shared. A full navigation (including the
  // prerender's page.goto per route) creates a fresh window, so this never
  // blocks a legitimate mount.
  const w = window as unknown as { __cmpAppStarted?: boolean };
  if (w.__cmpAppStarted) return;
  w.__cmpAppStarted = true;
  // M6 (re-audit 2026-11-15): GA4 loads here (skipped on
  // /admin/comments/) — it is no longer a static tag in index.html.
  // (AdSense was removed 2026-11-19 by user order; see thirdParty.ts.)
  loadThirdPartyScripts();
  const pathname = window.location.pathname;
  const urlLang = localeFromPath(pathname);
  // App also redirects '/' to the stored language preference on mount; if
  // the user previously chose a language, warm that dictionary too so the
  // redirect target renders without an English flash either.
  let storedLang: SupportedLang | null = null;
  if (pathname === '/' || pathname === '') {
    try {
      const stored = window.localStorage.getItem(LANG_STORAGE_KEY) ?? '';
      storedLang = isSupportedLang(stored) && stored !== 'en' ? stored : null;
    } catch {
      storedLang = null;
    }
  }
  const toPreload = [...new Set([urlLang, storedLang].filter((l): l is SupportedLang => l !== null))];
  // Tier C: the locale blog chunk loads only when the current route is a
  // blog route in that language. The stored-language redirect always lands
  // on the home page, so its locale loads without the blog chunk.
  const cleanPath = pathname.toLowerCase().replace(/\/+$/, '') || '/';
  const enPath = urlLang === 'en' || urlLang === null ? cleanPath : EN_PATH_BY_LANG[urlLang]?.[cleanPath];
  const blogRoute = enPath && isBlogEnPath(enPath) ? resolveBlogRoute(enPath) : null;
  // allSettled (not all): the preloads are independent — a failed page
  // chunk or article body must never cut the locale preload short. (A
  // single rejection here once aborted the locale load and broke hydration
  // on every non-EN route: the locale cache stayed empty, the first render
  // was English, React #418 discarded the SSR DOM. 2026-11-19.)
  await Promise.allSettled([
    ...toPreload.map((lang) =>
      preloadLocale(lang, { withBlog: lang === urlLang && blogRoute !== null }),
    ),
    preloadPage(pathname),
    // Tier B: the article body must be in the cache before the first
    // render, or hydration would render an empty body and the prerender
    // snapshot would ship without content.
    blogRoute?.kind === 'article' ? loadBlogBody(blogRoute.articleId) : Promise.resolve(),
    // Perf split 2026-11-19: the same for the LOCALE body on non-EN
    // article routes — without it hydration would render the English body
    // over the localized prerender (React #418). On EN routes the locale
    // loader is a no-op passthrough to the EN body.
    blogRoute?.kind === 'article' && urlLang !== null && urlLang !== 'en'
      ? loadBlogBodyLocale(urlLang, blogRoute.articleId)
      : Promise.resolve(),
  ]);
  const rootEl = document.getElementById('root')!;
  // Tier J (hydration fix, 2026-11-19): React adopts the prerendered DOM
  // instead of rebuilding it. The old createRoot + hide-until-settle
  // approach existed because App's first client render was English while
  // the prerender was localized (React error #418 — hydration text
  // mismatch — discarded the server DOM). That root cause is fixed by the
  // locale cache (src/locales/localeCache.ts): the locale was stored here
  // before first render, App's useState initializers read it
  // synchronously, so the first render is already localized and matches
  // the prerendered HTML. The hide is gone: the prerendered content stays
  // visible from first paint and hydration only wires up interactivity.
  // If hydration ever mismatches, React logs a console error and falls
  // back to a client render — the CLS probe in the verification step
  // watches for that (DE was 0.7852 with a ~7,400px footer jump before
  // the hide; it must stay < 0.1).
  hydrateRoot(rootEl, <App />);
}

